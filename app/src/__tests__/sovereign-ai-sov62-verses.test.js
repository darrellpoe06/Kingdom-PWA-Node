      const bent = TEXTS[place].split(NEARNESS).join('NEARNESS RELAXES THE STANDARD');
      expect(bent, `${place}: nothing was changed`).not.toBe(TEXTS[place]);
      expect(bent.includes(NEARNESS), `${place}: the nearness pin did not fire`).toBe(false);
