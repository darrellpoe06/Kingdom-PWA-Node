// =============================================================================
// corpus-coverage — is the service-video corpus WHOLE? Measured, never assumed
// =============================================================================
// Born from the 2026-07-10 gap Darrell photographed (DR-0135): the 0013 seed
// carried 125 of 335 channel videos — the generator dropped every undated video
// with a one-line filter, the debt was recorded only inside the migration's own
// comment, and NO instrument compared "what the channel has" against "what the
// app has." Every tab told the truth about a corpus that was never whole.
//
// The fix has three parts, and this module is the readout:
//   1. The generator now emits ALL videos (undated insert with NULL dates) and
//      writes the corpus MANIFEST (app/src/lib/corpus-manifest.json) — the
//      committed expected-list, regenerated by scripts/choir-youtube-backfill.mjs.
//   2. The corpus-reconcile workflow (dispatch; three brakes) regenerates the
//      manifest + full SQL on a runner and applies the idempotent backfill.
//   3. This module compares the LIVE choir_sermons rows against the manifest so
//      a partial backfill can never again hide as "that's all there is."
//
// HONESTY (DR-0076): a null/empty manifest reads "manifest not yet generated —
// run the reconcile", NEVER as full coverage. The recorded 125-of-335 facts
// carry their provenance until the first reconcile replaces them with a
// measured manifest. PURE (no React, no network).
// =============================================================================
import MANIFEST from './corpus-manifest.json';

// The measured facts of the gap as found (provenance: the 0013 file itself).
// These stand until the manifest is generated; then the manifest is the truth.
export const CORPUS_GAP_FOUND = {
  date: '2026-07-10',
  seedRows: 125,
  channelVideosAtGeneration: 335,
  provenance: 'infra/supabase/migrations-auto/0013-colg-sermon-backfill.sql header: "125 of 335 videos carried a parseable date; the rest ... are left for manual entry" — grep -c INSERT = 125',
};

export function corpusManifest() {
  return MANIFEST && typeof MANIFEST === 'object' ? MANIFEST : { generatedAt: null, videos: [] };
}

// corpusCoverage(liveRows) — compare live choir_sermons-shaped rows against the
// manifest. liveRows need only a videoId/video_id field.
export function corpusCoverage(liveRows, manifest = corpusManifest()) {
  const live = new Set();
  for (const r of Array.isArray(liveRows) ? liveRows : []) {
    const id = r && (r.videoId || r.video_id);
    if (id) live.add(id);
  }
  const expected = Array.isArray(manifest.videos) ? manifest.videos : [];
  const manifestReady = !!manifest.generatedAt && expected.length > 0;
  if (!manifestReady) {
    return {
      manifestReady: false,
      generatedAt: manifest.generatedAt || null,
      livePresent: live.size,
      expected: null,
      missing: [],
      // The recorded gap stands in for the unmeasured manifest — stated, never
      // smoothed over: last generation saw 335 on the channel, seeded 125.
      note: `Corpus manifest not yet generated — run the corpus-reconcile workflow. Recorded gap (${CORPUS_GAP_FOUND.date}): the ${CORPUS_GAP_FOUND.seedRows}-row seed vs ${CORPUS_GAP_FOUND.channelVideosAtGeneration} channel videos.`,
    };
  }
  const missing = expected.filter((v) => v && v.videoId && !live.has(v.videoId));
  return {
    manifestReady: true,
    generatedAt: manifest.generatedAt,
    livePresent: live.size,
    expected: expected.length,
    missing,
    note: missing.length === 0
      ? `Whole: all ${expected.length} channel videos are in the corpus (manifest ${manifest.generatedAt}).`
      : `${missing.length} of ${expected.length} channel videos are MISSING from the live corpus (manifest ${manifest.generatedAt}) — run the corpus-reconcile workflow.`,
  };
}
