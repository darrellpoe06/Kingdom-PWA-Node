/** The module with its benefits (unchanged when it has its own or is not listed). */
export function withBenefits(m) {
  if (Array.isArray(m.benefits) && m.benefits.length) return m;
  const b = B[m.id];
  return b ? { ...m, benefits: b } : m;
}
