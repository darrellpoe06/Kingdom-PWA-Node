// Pure: takes (bookName -> {chapters: string[][]}) loader results as an array
// of book objects, returns the measured shape. No I/O here — callers supply
// the corpus (the test reads the real files; a surface can fetch them).
export function measureBibleCorpus(books, termPatterns = PINNED_TERM_PATTERNS) {
  let chapters = 0;
  let verses = 0;
  const terms = Object.fromEntries(Object.keys(termPatterns).map((k) => [k, 0]));
  for (const book of books) {
    for (const ch of book.chapters) {
      chapters += 1;
      for (const v of ch) {
        verses += 1;
        const low = v.toLowerCase();
        for (const [key, pattern] of Object.entries(termPatterns)) {
          const m = low.match(new RegExp(pattern, 'g'));
          if (m) terms[key] += m.length;
        }
      }
    }
  }
  return { books: books.length, chapters, verses, terms };
}

