// Resolve one metric's why-refs against the real records. Every returned entry
// carries found:true|false — the surface renders a missing ref as missing.
export function resolveWhy(key, drById, lessons) {
  const w = WHY[key];
  if (!w) return { note: '', refs: [] };
  const principlesById = {};
  for (const p of (lessons && lessons.principles) || []) principlesById[p.id] = p;
  const refs = [];
  for (const id of w.drs) {
    const dr = drById && drById[id];
    refs.push(dr
      ? { kind: 'dr', id, found: true, title: dr.title || '', status: dr.status || '', date: dr.date || '' }
      : { kind: 'dr', id, found: false });
  }
  for (const id of w.principles) {
    const p = principlesById[id];
    refs.push(p
      ? { kind: 'principle', id, found: true, title: p.rule || '', detail: p.detail || '' }
      : { kind: 'principle', id, found: false });
  }
  return { note: w.note, refs };
}
