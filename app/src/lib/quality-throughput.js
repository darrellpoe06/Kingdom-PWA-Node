// One steward surface where the system's quantitative state (gates, coverage,
// debt, ops throughput) and its qualitative record (the DR, the principle, the
// concern) read TOGETHER — every number from a real artifact, every "why" from
// the real ledger. This module is the dependency-light core (unit-tested,
// DR-0076): normalizers for the build-time defines, throughput math over the
// real ops_commands rows, and the why-ref resolver that pairs each metric with
// its Decision Records + LESSONS-LEARNED principles.
//
// HONESTY RULES built in:
//   - a why-ref that does not resolve in the real ledger renders as MISSING
//     (found:false), never as a fabricated title;
//   - durations/averages are computed only over rows that carry both real
//     timestamps — a row without them contributes nothing;
//   - normalizers degrade to ok:false empties, so an absent artifact shows
//     "unavailable", never a painted zero pretending to be a measurement.

// --- build-time define normalizers --------------------------------------------

export function normalizeCensus(raw) {
  if (!raw || typeof raw !== 'object' || !raw.ok) {
    return { ok: false, files: 0, callSites: 0, eachSuites: 0, source: '' };
  }
  return {
    ok: true,
    files: Number(raw.files) || 0,
    callSites: Number(raw.callSites) || 0,
    eachSuites: Number(raw.eachSuites) || 0,
    source: raw.source || '',
  };
}

export function normalizeLessons(raw) {
  if (!raw || typeof raw !== 'object' || !raw.ok) {
    return { ok: false, principles: [], incidents: [], source: '' };
  }
  return {
    ok: true,
    principles: Array.isArray(raw.principles) ? raw.principles : [],
    incidents: Array.isArray(raw.incidents) ? raw.incidents : [],
    source: raw.source || '',
  };
}

// The DR ledger define (__DR_LEDGER__) is already shaped by vite.config; this
// only guards its absence (tests/SSR) and indexes it by id for the resolver.
export function drIndex(ledgerRaw) {
  const items = (ledgerRaw && Array.isArray(ledgerRaw.items)) ? ledgerRaw.items : [];
  const byId = {};
  for (const it of items) if (it && it.id) byId[it.id] = it;
  return byId;
}

// --- ops throughput (real ops_commands rows, toCommandShape-d) -----------------

export function commandDurationMs(cmd) {
  const a = Date.parse((cmd && cmd.startedAt) || '');
  const b = Date.parse((cmd && cmd.finishedAt) || '');
  if (!Number.isFinite(a) || !Number.isFinite(b) || b < a) return null;
  return b - a;
}

export function fmtMs(ms) {
  if (ms == null || !Number.isFinite(ms)) return '—';
  if (ms < 1000) return `${ms}ms`;
  const s = Math.round(ms / 1000);
  if (s < 60) return `${s}s`;
  const m = Math.floor(s / 60);
  return `${m}m ${s % 60}s`;
}

// Roll the recent command rows into the throughput tile: counts by outcome,
// measured run durations, and the roll-up status. `error` in the window is
// 'problem' (a run failed — that is red, not decoration); anything queued or
// running is 'attention' (in flight); an empty window is 'idle'.
export function opsThroughput(commands) {
  const rows = Array.isArray(commands) ? commands : [];
  const by = { done: 0, error: 0, skipped: 0, queued: 0, running: 0 };
  const durations = [];
  for (const c of rows) {
    if (by[c.status] != null) by[c.status] += 1;
    const d = commandDurationMs(c);
    if (d != null && (c.status === 'done' || c.status === 'error')) durations.push(d);
  }
  const avgMs = durations.length
    ? Math.round(durations.reduce((a, b) => a + b, 0) / durations.length)
    : null;
  let status = 'idle';
  let label = 'No commands yet';
  if (by.error > 0) { status = 'problem'; label = `${by.error} failed`; }
  else if (by.queued + by.running > 0) { status = 'attention'; label = `${by.queued + by.running} in flight`; }
  else if (by.done > 0) { status = 'good'; label = `${by.done} completed`; }
  return { total: rows.length, ...by, avgMs, status, label };
}

// --- surface-audit tile (audit-findings.json, generated by DR-0086) ------------

export function auditTile(artifact) {
  const s = (artifact && artifact.summary) || {};
  const open = Number(s.total) || 0;
  const critical = Number(s.critical) || 0;
  const resolved = Number(artifact && artifact.resolvedSinceLast) || 0;
  const surfaces = Number(artifact && artifact.coverage && artifact.coverage.surfacesTotal) || 0;
  let status = 'good';
  let label = 'No open findings';
  if (critical > 0) { status = 'problem'; label = `${critical} critical`; }
  else if (open > 0) { status = 'attention'; label = `${open} open`; }
  return {
    open, critical, resolved, surfaces,
    generatedAt: (artifact && artifact.generatedAt) || null,
    status, label,
  };
}

// --- harvest tile (fetchLedger result — the same math the Harvest page shows) --

export function harvestTile(ledger) {
  if (!ledger || !Number.isFinite(Number(ledger.videos))) {
    return { ok: false, status: 'idle', label: 'Not loaded', videos: 0, transcribed: 0, avgPct: 0, fully: 0 };
  }
  const videos = Number(ledger.videos) || 0;
  const transcribed = Number(ledger.transcribedVideos) || 0;
  const avgPct = Number(ledger.avgPct) || 0;
  const fully = Number(ledger.fullyHarvested) || 0;
  const orphans = Number(ledger.orphans) || 0;
  let status = 'attention';
  let label = `${avgPct}% avg coverage`;
  if (videos === 0) { status = 'idle'; label = 'No corpus yet'; }
  else if (orphans > 0) { status = 'problem'; label = `${orphans} orphan${orphans === 1 ? '' : 's'}`; }
  else if (avgPct >= 100) { status = 'good'; label = 'Fully mined'; }
  return { ok: true, videos, transcribed, avgPct, fully, orphans, status, label };
}

