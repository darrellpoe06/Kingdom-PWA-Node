// =============================================================================
// gen-scripture-web — fetch the World English Bible (WEB, Public Domain) text
// for the SAME reference set the KJV file already carries, verbatim, and emit
// app/src/lib/scripture-web.js in the identical shape to scripture-kjv.js.
// =============================================================================
// DR-0076 (Verification Doctrine): scripture text is FETCHED, never typed from
// memory. WEB is dedicated to the public domain (eBible.org / Michael Paul
// Johnson), so its full text is reproducible and modifiable. Whitespace is
// normalized ONLY (collapse runs to a single space, trim) — never reworded.
//
//   node app/scripts/gen-scripture-web.mjs
//
// Re-runnable. On any fetch failure the ref is recorded and the run still emits
// the file with what it got plus a FAILURES comment, so a partial set is honest.
// =============================================================================
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoApp = path.resolve(__dirname, '..');
const KJV_PATH = path.join(repoApp, 'src/lib/scripture-kjv.js');
const OUT_PATH = path.join(repoApp, 'src/lib/scripture-web.js');

function refsFromKjv() {
  const src = fs.readFileSync(KJV_PATH, 'utf8');
  const m = src.match(/"[^"]+":/g) || [];
  return [...new Set(m.map((s) => s.slice(1, -2)))];
}

function norm(s) {
  return String(s || '').replace(/\s+/g, ' ').trim();
}

async function fetchWeb(ref) {
  const url = `https://bible-api.com/${encodeURIComponent(ref)}?translation=web`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const j = await res.json();
  if (!j || !j.text) throw new Error('no text');
  if (j.translation_id && j.translation_id !== 'web') throw new Error(`wrong translation ${j.translation_id}`);
  return norm(j.text);
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function main() {
  const refs = refsFromKjv();
  const out = {};
  const failures = [];
  let i = 0;
  for (const ref of refs) {
    i += 1;
    let ok = false;
    for (let attempt = 0; attempt < 3 && !ok; attempt += 1) {
      try {
        out[ref] = await fetchWeb(ref);
        ok = true;
      } catch (e) {
        if (attempt === 2) failures.push({ ref, error: String(e.message || e) });
        else await sleep(3000);
      }
    }
    process.stderr.write(`[${i}/${refs.length}] ${ref} ${ok ? 'OK' : 'FAIL'}\n`);
    await sleep(2200); // stay under bible-api.com rate limit (~15 / 30s)
  }

  const keys = Object.keys(out).sort((a, b) => a.localeCompare(b));
  const lines = [];
  lines.push('// =============================================================================');
  lines.push('// scripture-web — GENERATED verbatim World English Bible text (DO NOT HAND-EDIT)');
  lines.push('// =============================================================================');
  lines.push('// Every entry below was fetched from bible-api.com (translation=web, "Public');
  lines.push('// Domain") and normalized for whitespace ONLY (runs collapsed to a single space,');
  lines.push('// trimmed) -- never reworded. The World English Bible is dedicated to the PUBLIC');
  lines.push('// DOMAIN (eBible.org / Michael Paul Johnson): its full modern-English text may be');
  lines.push('// reproduced, modified, and redistributed without licensing limits. This is the');
  lines.push('// sovereign MODERN-ENGLISH base text; scripture-kjv.js is the 1611 base. Both are');
  lines.push('// the SCRIPTURE TEXT layer -- the clarification layer (study-edition.js) is held');
  lines.push('// structurally separate and is never substituted into this text (DR-0076).');
  lines.push('//');
  lines.push(`// Generated by app/scripts/gen-scripture-web.mjs from the ${refs.length} references in`);
  lines.push('// scripture-kjv.js. Re-run that script to regenerate; do not type Scripture by hand.');
  if (failures.length) {
    lines.push('//');
    lines.push(`// FAILURES (${failures.length}) -- these refs did not resolve and are omitted:`);
    for (const f of failures) lines.push(`//   ${f.ref}: ${f.error}`);
  }
  lines.push('// =============================================================================');
  lines.push('');
  lines.push('export const WEB = {');
  for (const k of keys) {
    const esc = out[k].replace(/\\/g, '\\\\').replace(/"/g, '\\"');
    lines.push(`  "${k}": "${esc}",`);
  }
  lines.push('};');
  lines.push('');
  fs.writeFileSync(OUT_PATH, lines.join('\n'));
  process.stderr.write(`\nWrote ${keys.length} verses to ${OUT_PATH}; ${failures.length} failures.\n`);
}

main().catch((e) => { process.stderr.write(`FATAL ${e}\n`); process.exit(1); });
