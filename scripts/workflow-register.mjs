#!/usr/bin/env node
// =============================================================================
// workflow-register — every workflow, what fires it, what brakes it, how big
// it is: read from the YAML, kept honest by the build (DR-1342, DR-1330 D13)
// =============================================================================
// Darrell, 2026-11-05: "Clean functions and workflows..." The review measured
// 95 workflows and 21,896 lines of YAML with nothing recording which ones
// still ran or which carried their brakes. This reads every workflow file and
// writes app/src/lib/workflow-register.json: name, purpose (its first comment
// line), triggers, crons, whether it carries a concurrency group, a timeout
// and a permissions block (the three-brakes rule, CLAUDE.md), the reusable
// workflow it calls, and its line count. `--check` (the guards leg) fails
// when the committed file differs from the YAML, and when the total line
// count grows past scripts/workflow-budget.json (a ratchet that only goes
// down with --generate, like the monolith's). Admin → Endpoints & stores
// renders it. Pure functions exported for vitest; proven to catch on a
// fixture and on a stale file.
// =============================================================================
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = 'app/src/lib/workflow-register.json';
export const BUDGET = 'scripts/workflow-budget.json';

/** A small reader for the handful of top-level YAML facts a workflow declares (no YAML library in scripts/). */
export function factsOf(file, text) {
  const lines = text.split('\n');
  const name = (text.match(/^name:\s*(.+)$/m) || [])[1]?.trim().replace(/^['"]|['"]$/g, '') || file;
  const purpose = (lines.find((l) => /^#\s*\S/.test(l) && !/^#\s*=+\s*$/.test(l)) || '').replace(/^#\s*/, '').trim().slice(0, 160);
  // The `on:` block: top-level keys until the next top-level key.
  const onStart = lines.findIndex((l) => /^(on|"on"|'on'|true):\s*(\{\s*\}|$|\[)/.test(l) || /^on:\s*\S/.test(l));
  const triggers = [];
  const crons = [];
  if (onStart >= 0) {
    const inline = lines[onStart].match(/^on:\s*\[([^\]]*)\]/);
    if (inline) triggers.push(...inline[1].split(',').map((s) => s.trim()).filter(Boolean));
    const single = lines[onStart].match(/^on:\s*([a-z_]+)\s*$/);
    if (single) triggers.push(single[1]);
    for (let i = onStart + 1; i < lines.length; i++) {
      const l = lines[i];
      if (/^\S/.test(l) && !/^\s*#/.test(l)) break;
      const key = l.match(/^  ([a-z_]+):/);
      if (key) triggers.push(key[1]);
      const cron = l.match(/^\s+-\s*cron:\s*['"]?([^'"#]+?)['"]?\s*(#.*)?$/);
      if (cron) crons.push(cron[1].trim());
    }
  }
  const timeouts = [...text.matchAll(/^\s+timeout-minutes:\s*(\S+)/gm)].map((m) => m[1]);
  const calls = [...text.matchAll(/^\s+uses:\s*\.\/\.github\/workflows\/([^\s@]+)/gm)].map((m) => m[1]);
  return {
    file, name, purpose, triggers: [...new Set(triggers)], crons,
    brakes: { concurrency: /^concurrency:/m.test(text), timeout: timeouts.length > 0, permissions: /^permissions:/m.test(text) },
    calls, lines: lines.length,
  };
}

export function build(files) {
  const workflows = Object.entries(files).map(([f, t]) => factsOf(f, t)).sort((a, b) => a.file.localeCompare(b.file));
  const totalLines = workflows.reduce((s, w) => s + w.lines, 0);
  return {
    _comment: 'GENERATED by scripts/workflow-register.mjs from .github/workflows (DR-1342). Do not edit; run `node scripts/workflow-register.mjs --write`. The guards leg fails when this file is stale.',
    counts: {
      workflows: workflows.length,
      totalLines,
      dispatchOnly: workflows.filter((w) => w.triggers.length === 1 && w.triggers[0] === 'workflow_dispatch').length,
      scheduled: workflows.filter((w) => w.triggers.includes('schedule')).length,
      reusable: workflows.filter((w) => w.triggers.includes('workflow_call')).length,
      callers: workflows.filter((w) => w.calls.length).length,
      withoutConcurrency: workflows.filter((w) => !w.brakes.concurrency && !w.triggers.includes('workflow_call')).length,
      withoutTimeout: workflows.filter((w) => !w.brakes.timeout && !w.calls.length).length,
      withoutPermissions: workflows.filter((w) => !w.brakes.permissions).length,
    },
    workflows,
  };
}

export function judgeBudget(totalLines, budget) {
  return totalLines > budget.totalLines ? [`.github/workflows: ${totalLines} lines, over the ceiling of ${budget.totalLines} (clean a workflow, or raise the ceiling by hand with a reason)`] : [];
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const dir = join(ROOT, '.github/workflows');
  const files = Object.fromEntries(readdirSync(dir).filter((f) => /\.ya?ml$/.test(f)).sort().map((f) => [f, readFileSync(join(dir, f), 'utf8')]));
  const next = JSON.stringify(build(files), null, 2) + '\n';
  const outPath = join(ROOT, OUT);
  const budgetPath = join(ROOT, BUDGET);
  const register = JSON.parse(next);
  if (process.argv.includes('--write')) {
    writeFileSync(outPath, next);
    console.log(`workflow-register: wrote ${OUT} — ${register.counts.workflows} workflows, ${register.counts.totalLines} lines.`);
    process.exit(0);
  }
  if (process.argv.includes('--generate')) {
    const budget = existsSync(budgetPath) ? JSON.parse(readFileSync(budgetPath, 'utf8')) : { totalLines: register.counts.totalLines };
    budget.totalLines = Math.min(budget.totalLines, register.counts.totalLines);
    writeFileSync(budgetPath, JSON.stringify({ _comment: 'workflow-register (DR-1342): the total line count of .github/workflows may only go DOWN; re-freeze lower with `node scripts/workflow-register.mjs --generate`. To RAISE it, edit by hand with a one-line reason here.', raises: budget.raises || [], totalLines: budget.totalLines }, null, 2) + '\n');
    console.log(`workflow-register: re-froze the YAML ceiling at ${budget.totalLines} lines, down only.`);
    process.exit(0);
  }
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
  const failures = [];
  if (current !== next) failures.push(`${OUT} is STALE against .github/workflows — run \`node scripts/workflow-register.mjs --write\` and commit it`);
  const budget = JSON.parse(readFileSync(budgetPath, 'utf8'));
  failures.push(...judgeBudget(register.counts.totalLines, budget));
  if (failures.length) { console.error(`workflow-register: ${failures.length} finding(s):\n  ${failures.join('\n  ')}`); process.exit(1); }
  const c = register.counts;
  console.log(`workflow-register: OK — ${c.workflows} workflows, ${c.totalLines} lines (ceiling ${budget.totalLines}); ${c.dispatchOnly} dispatch-only, ${c.scheduled} scheduled, ${c.callers} on the shared harness; without a concurrency group ${c.withoutConcurrency}, without a timeout ${c.withoutTimeout}, without permissions ${c.withoutPermissions}.`);
}
