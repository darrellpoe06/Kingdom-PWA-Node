// =============================================================================
// help-freshness — the gate that keeps the Help tab CURRENT (DR-0076 / DR-0086)
// =============================================================================
// The two-tier self-explaining layer only keeps surfaces LIGHT if the DEEP Help
// entry stays current (Darrell 2026-07-01). This makes "every self-explaining
// surface has a CURRENT Help entry" a checkable, build-failing condition:
//
//   for each surface in surface-help.js SURFACE_HELP:
//     · it must have a Help entry (help-content.js HELP[topic])        -> else MISSING
//     · the recorded fingerprint (help-freshness.json) must equal the
//       surface's current about fingerprint                            -> else STALE
//
// A surface's about changes -> its fingerprint changes -> the recorded one no
// longer matches -> STALE -> the gate fails until someone updates the Help entry
// and runs `--sync` to reconcile. A new surface with no Help entry -> MISSING ->
// flagged for a human to author the deep entry (auto-create isn't safe to fake).
//
// Least-human: `--sync` reconciles every topic that HAS an entry in one command;
// only genuinely-absent deep entries need a person. The proactive surface audit
// (surface-audit.mjs) also files STALE/MISSING as Concerns so it is enforced on
// the NAS loop, not only in CI.
//
// CLI:
//   node scripts/help-freshness.mjs            # report
//   node scripts/help-freshness.mjs --check    # exit 1 if any stale/missing
//   node scripts/help-freshness.mjs --sync     # reconcile fingerprints, flag missing
// =============================================================================

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SURFACE_HELP, aboutFingerprint } from '../app/src/lib/surface-help.js';
import { HELP } from '../app/src/lib/help-content.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const RECORDS_PATH = join(ROOT, 'app/src/lib/help-freshness.json');

export function loadRecords() {
  try { return JSON.parse(readFileSync(RECORDS_PATH, 'utf8')).topics || {}; }
  catch { return {}; }
}

// The full freshness picture: one row per SURFACE_HELP topic.
export function computeFreshness(records = loadRecords(), help = HELP, registry = SURFACE_HELP) {
  const rows = Object.entries(registry).map(([topic, about]) => {
    const hasEntry = !!(help && help[topic]);
    const current = aboutFingerprint(about);
    const recorded = records[topic] || null;
    let status;
    if (!hasEntry) status = 'missing-entry';
    else if (recorded == null) status = 'unrecorded';
    else if (recorded !== current) status = 'stale';
    else status = 'current';
    return { topic, hasEntry, current, recorded, status };
  });
  const bad = rows.filter((r) => r.status !== 'current');
  return {
    rows,
    ok: bad.length === 0,
    stale: rows.filter((r) => r.status === 'stale' || r.status === 'unrecorded'),
    missing: rows.filter((r) => r.status === 'missing-entry'),
  };
}

// The reconciled records the JSON should hold for topics that HAVE a Help entry.
export function buildRecords(help = HELP, registry = SURFACE_HELP) {
  const topics = {};
  for (const [topic, about] of Object.entries(registry)) {
    if (help && help[topic]) topics[topic] = aboutFingerprint(about);
  }
  return { _comment: 'GENERATED by scripts/help-freshness.mjs --sync. Each value is the fingerprint of the surface about (surface-help.js) that the Help entry (help-content.js) was last reconciled to. A mismatch means the surface changed and its Help entry is due for review.', topics };
}

// Audit-finding-shaped objects (for surface-audit.mjs to file to the Concerns board).
export function findingsFromFreshness(fr = computeFreshness()) {
  const out = [];
  for (const r of fr.missing) {
    out.push({
      surface: r.topic, surfaceLabel: r.topic, item: 'help-missing',
      title: `Self-explaining surface "${r.topic}" has no Help entry`,
      dimension: 'self-explaining', severity: 'high', detail: 'inline about exists; deep Help entry is absent',
      fix: `Author a Help entry HELP['${r.topic}'] (help-content.js), then run: node scripts/help-freshness.mjs --sync`,
      detectedBy: 'help-freshness', key: `help::${r.topic}::missing`,
    });
  }
  for (const r of fr.stale) {
    out.push({
      surface: r.topic, surfaceLabel: r.topic, item: 'help-stale',
      title: `Help entry for "${r.topic}" is stale (surface changed)`,
      dimension: 'self-explaining', severity: 'medium', detail: `about fingerprint ${r.current} != recorded ${r.recorded || 'none'}`,
      fix: `Review HELP['${r.topic}'] against the current surface, then run: node scripts/help-freshness.mjs --sync`,
      detectedBy: 'help-freshness', key: `help::${r.topic}::stale`,
    });
  }
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const arg = process.argv[2];
  if (arg === '--sync') {
    const records = buildRecords();
    writeFileSync(RECORDS_PATH, JSON.stringify(records, null, 2) + '\n');
    const fr = computeFreshness(records.topics);
    console.log(`# help-freshness --sync\nReconciled ${Object.keys(records.topics).length} topic(s) into ${relative(ROOT, RECORDS_PATH)}.`);
    if (fr.missing.length) console.log(`FLAGGED (need a human to author the deep entry): ${fr.missing.map((r) => r.topic).join(', ')}`);
    process.exit(0);
  }
  const fr = computeFreshness();
  if (arg === '--check') {
    if (fr.ok) { console.log('# help-freshness --check\nPASS — every self-explaining surface has a current Help entry.'); process.exit(0); }
    console.error('# help-freshness --check\nFAIL — Help is out of date (clutter risk):');
    for (const r of [...fr.missing, ...fr.stale]) console.error(`  - ${r.topic}: ${r.status}`);
    console.error('Fix: update the Help entries, then run `node scripts/help-freshness.mjs --sync`.');
    process.exit(1);
  }
  console.log('# help-freshness');
  for (const r of fr.rows) console.log(`  ${r.status === 'current' ? 'OK  ' : 'DUE '} ${r.topic} — ${r.status}`);
  if (!existsSync(RECORDS_PATH)) console.log('(no help-freshness.json yet — run --sync)');
}
